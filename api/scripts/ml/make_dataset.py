"""Build the 3-class training set: human / ai / ai_paraphrased.

The paraphrased class is what makes Swipe catch "humanised" AI text — you can't
learn it without examples, so we manufacture them: take AI text and run it through
a paraphraser (a stand-in for QuillBot / Undetectable.ai).

Human + AI pairs come from HC3 (human vs ChatGPT answers to the same questions).
Newer `datasets` versions refuse script-based loaders, so we load HC3 from its
Parquet mirror; if that is unavailable we fall back to the RAID benchmark, which
is plain Parquet and always loads.

Writes data/ai_dataset.jsonl with {text, label}. Run on Colab (a GPU speeds up the
paraphraser). Scale --n up once the pipeline works.

    pip install datasets transformers torch sentencepiece
    python scripts/ml/make_dataset.py --n 3000
"""
from __future__ import annotations
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
import argparse, json
from pathlib import Path


def _load_hc3_pairs():
    """Yield (human_text, ai_text) pairs from HC3, via Parquet (no loader script)."""
    from datasets import load_dataset
    attempts = [
        # Parquet mirror auto-generated by the Hub — bypasses the HC3.py script.
        dict(path="Hello-SimpleAI/HC3", name="all", split="train",
             revision="refs/convert/parquet"),
        # Some mirrors expose the data directly as parquet files.
        dict(path="Hello-SimpleAI/HC3", split="train",
             revision="refs/convert/parquet"),
    ]
    last = None
    for kw in attempts:
        try:
            ds = load_dataset(**kw)
            for ex in ds:
                humans = ex.get("human_answers") or []
                ais = ex.get("chatgpt_answers") or []
                if humans and ais:
                    yield humans[0], ais[0]
            return
        except Exception as e:  # noqa: BLE001
            last = e
            continue
    raise RuntimeError(f"HC3 could not be loaded via parquet: {last}")


def _load_raid_pairs():
    """Fallback: RAID has human + model generations. Pair them loosely by pulling
    human rows and AI rows separately (they aren't 1:1, but we only need class
    examples, not aligned pairs)."""
    from datasets import load_dataset
    ds = load_dataset("liamdugan/raid", split="train", streaming=True)
    humans, ais = [], []
    for ex in ds:
        t = ex.get("generation") or ""
        if len(t.split()) < 40:
            continue
        if ex.get("model") == "human":
            humans.append(t)
        else:
            ais.append(t)
        if len(humans) > 20000 and len(ais) > 20000:
            break
    for h, a in zip(humans, ais):
        yield h, a


def main(n: int):
    from transformers import pipeline

    Path("data").mkdir(exist_ok=True)
    out = Path("data/ai_dataset.jsonl")

    try:
        pairs = _load_hc3_pairs()
        source = "HC3"
        first = next(pairs)                      # force the first item to catch load errors now
        import itertools
        pairs = itertools.chain([first], pairs)
    except Exception as e:                        # noqa: BLE001
        print(f"[make_dataset] HC3 unavailable ({e}); falling back to RAID.")
        pairs = _load_raid_pairs()
        source = "RAID"

    para = pipeline("text2text-generation",
                    model="humarin/chatgpt_paraphraser_on_T5_base", max_length=256)

    rows = []
    made = {"human": 0, "ai": 0, "para": 0}
    for human_text, ai_text in pairs:
        if made["human"] < n and len(human_text.split()) > 40:
            rows.append({"text": human_text, "label": 0}); made["human"] += 1
        if made["ai"] < n and len(ai_text.split()) > 40:
            rows.append({"text": ai_text, "label": 1}); made["ai"] += 1
            if made["para"] < n:
                p = para(ai_text[:900])[0]["generated_text"]
                rows.append({"text": p, "label": 2}); made["para"] += 1
        if all(v >= n for v in made.values()):
            break

    with out.open("w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    print(f"wrote {len(rows)} rows to {out} from {source}: {made}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=3000, help="target rows per class")
    main(ap.parse_args().n)
